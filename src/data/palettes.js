export function getPalette(paletteId = 'classic-48') {
  return PALETTES.find((palette) => palette.id === paletteId) || PALETTES[0]
}

export function getColorMap(paletteId) {
  return getPalette(paletteId).colors.reduce((map, color) => {
    map[color.id] = color
    return map
  }, {})
}
